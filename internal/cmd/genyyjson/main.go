package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
)

const generatedHeader = `// Code generated by genyyjson; DO NOT EDIT.
// Source: yyjson/src/yyjson.c via modernc.org/ccgo/v4.
`

const defaultTargets = "linux/amd64,linux/arm64"

type generationTarget struct {
	goos   string
	goarch string
}

func main() {
	check := flag.Bool("check", false, "fail if generated output differs from checked-in files")
	outDirFlag := flag.String("out-dir", "", "directory for generated output")
	targetsFlag := flag.String("targets", defaultTargets, "comma-separated GOOS/GOARCH targets")
	flag.Parse()

	goRoot, err := findGoRoot()
	if err != nil {
		fatal(err)
	}
	srcDir := filepath.Join(goRoot, "yyjson", "src")
	outDir := filepath.Join(goRoot, "internal", "yyjsonc")
	if *outDirFlag != "" {
		outDir = *outDirFlag
	}
	targets, err := parseTargets(*targetsFlag)
	if err != nil {
		fatal(err)
	}

	tmp, err := os.MkdirTemp("", "yyjson-gen-*")
	if err != nil {
		fatal(err)
	}
	defer func() {
		_ = os.RemoveAll(tmp)
	}()

	shim := filepath.Join(tmp, "yyjson_go_shim.c")
	if err := os.WriteFile(shim, []byte(shimSource), 0o644); err != nil {
		fatal(err)
	}
	if err := copyModuleFiles(goRoot, tmp); err != nil {
		fatal(err)
	}

	if err := os.MkdirAll(outDir, 0o755); err != nil {
		fatal(err)
	}
	ccgo, err := ccgoTool(goRoot)
	if err != nil {
		fatal(err)
	}
	for _, target := range targets {
		if err := generateTarget(goRoot, ccgo, srcDir, shim, outDir, tmp, target.goos, target.goarch, *check); err != nil {
			fatal(err)
		}
	}
}

func parseTargets(raw string) ([]generationTarget, error) {
	var targets []generationTarget
	for _, item := range strings.Split(raw, ",") {
		item = strings.TrimSpace(item)
		if item == "" {
			continue
		}
		goos, goarch, ok := strings.Cut(item, "/")
		if !ok || goos == "" || goarch == "" || strings.Contains(goarch, "/") {
			return nil, fmt.Errorf("invalid target %q, want GOOS/GOARCH", item)
		}
		targets = append(targets, generationTarget{goos: goos, goarch: goarch})
	}
	if len(targets) == 0 {
		return nil, fmt.Errorf("no generation targets")
	}
	return targets, nil
}

func generateTarget(goRoot, ccgo, srcDir, shim, outDir, tmp, goos, goarch string, check bool) error {
	tmpOut := filepath.Join(tmp, fmt.Sprintf("yyjson_%s_%s.go", goos, goarch))
	outFile := filepath.Join(outDir, fmt.Sprintf("yyjson_%s_%s.go", goos, goarch))
	sidecars := ccgoSidecars(goRoot)
	if err := removeFiles(sidecars); err != nil {
		return err
	}
	args := []string{
		"--package-name", "yyjsonc",
		"--prefix-external", "X",
		"--prefix-typename", "T",
		"-o", tmpOut,
		"-I" + srcDir,
		"-Dyyjson_inline=",
		"-U__SIZEOF_INT128__",
		"-D__clang__=1",
		"-ignore-unsupported-alignment",
		filepath.Join(srcDir, "yyjson.c"),
		shim,
	}
	cmd := exec.Command(ccgo, args...)
	cmd.Dir = tmp
	cmd.Env = append(os.Environ(), "TARGET_GOOS="+goos, "TARGET_GOARCH="+goarch)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	runErr := cmd.Run()
	cleanupErr := removeFiles(sidecars)
	if runErr != nil {
		if cleanupErr != nil {
			return fmt.Errorf("run ccgo for %s/%s: %w; cleanup sidecars: %v", goos, goarch, runErr, cleanupErr)
		}
		return fmt.Errorf("run ccgo for %s/%s: %w", goos, goarch, runErr)
	}
	if cleanupErr != nil {
		return cleanupErr
	}

	data, err := os.ReadFile(tmpOut)
	if err != nil {
		return fmt.Errorf("read generated output %s: %w", tmpOut, err)
	}
	data = normalizeGenerated(data)

	if old, err := os.ReadFile(outFile); err == nil && bytes.Equal(old, data) {
		return nil
	}
	if check {
		return fmt.Errorf("%s is stale; run %q", outFile, "go generate ./...")
	}
	if err := os.WriteFile(outFile, data, 0o644); err != nil {
		return fmt.Errorf("write generated output %s: %w", outFile, err)
	}
	return nil
}

func ccgoTool(goRoot string) (string, error) {
	cmd := exec.Command("go", "tool", "-n", "modernc.org/ccgo/v4")
	cmd.Dir = goRoot
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("resolve ccgo tool: %w: %s", err, bytes.TrimSpace(stderr.Bytes()))
	}
	path := string(bytes.TrimSpace(out))
	if path == "" {
		return "", fmt.Errorf("resolve ccgo tool: empty tool path")
	}
	return path, nil
}

func copyModuleFiles(goRoot, tmp string) error {
	for _, name := range []string{"go.mod", "go.sum"} {
		data, err := os.ReadFile(filepath.Join(goRoot, name))
		if err != nil {
			return fmt.Errorf("read %s: %w", name, err)
		}
		if err := os.WriteFile(filepath.Join(tmp, name), data, 0o644); err != nil {
			return fmt.Errorf("write temporary %s: %w", name, err)
		}
	}
	return nil
}

func findGoRoot() (string, error) {
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		return "", fmt.Errorf("resolve generator source path")
	}
	return filepath.Clean(filepath.Join(filepath.Dir(file), "..", "..", "..")), nil
}

func normalizeHeader(data []byte) []byte {
	if i := bytes.IndexByte(data, '\n'); i >= 0 {
		return append([]byte(generatedHeader), data[i+1:]...)
	}
	return append([]byte(generatedHeader), data...)
}

func normalizeGenerated(data []byte) []byte {
	data = normalizeHeader(data)
	data = dropHostCompilerDefinitions(data)
	return disableGeneratedCheckptr(data)
}

func ccgoSidecars(goRoot string) []string {
	return []string{
		filepath.Join(goRoot, "yyjson.o.go"),
		filepath.Join(goRoot, "yyjson_go_shim.o.go"),
	}
}

func removeFiles(paths []string) error {
	for _, path := range paths {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("remove %s: %w", path, err)
		}
	}
	return nil
}

// ccgo emits host compiler definitions as unused Go declarations, which makes
// generated output depend on the compiler and architecture used to run it.
func dropHostCompilerDefinitions(data []byte) []byte {
	out := make([]byte, 0, len(data))
	for _, line := range bytes.SplitAfter(data, []byte("\n")) {
		if bytes.HasPrefix(line, []byte("const __")) ||
			bytes.HasPrefix(line, []byte("const FP_FAST_")) ||
			bytes.HasPrefix(line, []byte("type T__predefined_")) {
			continue
		}
		out = append(out, line...)
	}
	return out
}

// disableGeneratedCheckptr marks generated functions that reference
// unsafe.Pointer. modernc/libc exposes C pointers as uintptr values, which is
// expected for ccgo output but intentionally outside Go checkptr's model.
func disableGeneratedCheckptr(data []byte) []byte {
	const directive = "//go:nocheckptr\n"
	out := make([]byte, 0, len(data))
	lines := bytes.SplitAfter(data, []byte("\n"))
	for i := 0; i < len(lines); {
		line := lines[i]
		if !bytes.HasPrefix(line, []byte("func ")) {
			out = append(out, line...)
			i++
			continue
		}

		start := i
		i++
		for i < len(lines) && !bytes.HasPrefix(lines[i], []byte("func ")) {
			i++
		}
		fn := bytes.Join(lines[start:i], nil)
		if bytes.Contains(fn, []byte("unsafe.Pointer")) && !lastLineIsDirective(out, directive) {
			out = append(out, directive...)
		}
		out = append(out, fn...)
	}
	return out
}

func lastLineIsDirective(data []byte, directive string) bool {
	if len(data) < len(directive) {
		return false
	}
	return bytes.Equal(data[len(data)-len(directive):], []byte(directive))
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "genyyjson:", err)
	os.Exit(1)
}

